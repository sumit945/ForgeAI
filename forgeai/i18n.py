def refusal_messages(escalation: str) -> dict[str, str]:
    return {code: msg.replace("{x}", escalation) for code, msg in REFUSALS.items()}


def refusal_heads() -> list[str]:
    """Normalised opening clause of every refusal (before the contact sentence) - lets the judge recognise a localised refusal."""
    heads = []
    for msg in REFUSALS.values():
        first = normalize_text(msg.split("{x}")[0])
        for sep in (". ", "। ", "।", ". "):
            first = first.split(sep)[0]
        heads.append(first.strip(" ."))
    return heads


