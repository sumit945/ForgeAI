"""Stage 7 - Honest reporting. The report is assembled by code from measured data (no LLM prose), so it cannot flatter the agent."""
from __future__ import annotations

import math


def pct(x) -> str:
    return "n/a" if x is None else f"{x * 100:.0f}%"


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0, c - h), min(1, c + h))


def scorecard_markdown(base: dict, history: list[dict], final_sc: dict) -> str:
    rows = [f"| 0 (baseline) | - | {pct(base['scorecard']['dev']['pass_rate'])} | {pct(base['scorecard']['holdout']['pass_rate'])} | {pct(base['scorecard']['overall']['pass_rate'])} | generated agent, untouched |"]
    for h in history:
        s = h["score_after"]
        rows.append(f"| {h['iteration']} | {'accepted' if h['accepted'] else 'reverted'} | {pct(s['dev'])} | {pct(s['holdout'])} | {pct(s['overall'])} | {len(h['changes'])} change(s), fixed {len(h['fixed'])}, regressed {len(h['regressed'])} |")
    o, d, hd = final_sc["overall"], final_sc["dev"], final_sc["holdout"]
    cat = "\n".join(f"| {k} | {v['n']} | {pct(v['pass_rate'])} |" for k, v in final_sc["by_category"].items())
    return f"""# Scorecard

## Per iteration (pass = correct AND grounded AND refused-when-it-should)
| Iteration | Outcome | Dev | Hold-out | Overall | Note |
|---|---|---|---|---|---|
{chr(10).join(rows)}

Dev = the split the optimizer sees. Hold-out = never used for any decision; a large dev/hold-out gap means the loop overfitted.

## Final metrics (accepted definition)
| Metric | Overall | Dev | Hold-out |
|---|---|---|---|
| Cases | {o['n']} | {d['n']} | {hd['n']} |
| Pass rate | {pct(o['pass_rate'])} | {pct(d['pass_rate'])} | {pct(hd['pass_rate'])} |
| Correct (answerable) | {pct(o['correct_rate'])} | {pct(d['correct_rate'])} | {pct(hd['correct_rate'])} |
| Grounded (answerable) | {pct(o['grounded_rate'])} | {pct(d['grounded_rate'])} | {pct(hd['grounded_rate'])} |
| Refusal recall (should refuse -> refused) | {pct(o['refusal_recall'])} | {pct(d['refusal_recall'])} | {pct(hd['refusal_recall'])} |
| Wrong-refusal rate (answerable -> refused) | {pct(o['wrong_refusal_rate'])} | {pct(d['wrong_refusal_rate'])} | {pct(hd['wrong_refusal_rate'])} |
| Retrieval hit rate | {pct(o['retrieval_hit_rate'])} | {pct(d['retrieval_hit_rate'])} | {pct(hd['retrieval_hit_rate'])} |
| Model broke output contract (before code-side repair) | {pct(o['contract_violation_rate'])} | {pct(d['contract_violation_rate'])} | {pct(hd['contract_violation_rate'])} |

## By category
| Category | n | Pass rate |
|---|---|---|
{cat}
"""


def build_report(ctx: dict) -> str:
    req, gr, defn, opt, ev, cal = ctx["requirements"], ctx["groundability"], ctx["definition"], ctx["optimizer"], ctx["evalset"], ctx["calibration"]
    base, hist, fsc = opt["baseline"], opt["history"], opt["final_scorecard"]
    o = fsc["overall"]
    k = round((o["pass_rate"] or 0) * o["n"])
    lo, hi = wilson(k, o["n"])
    lines = [f"# ForgeAI run report - {defn['name']}", ""]
    lines += [
        f"**Brief:** {req['brief']}", "",
        f"**Result:** final overall pass rate **{pct(o['pass_rate'])}** ({k}/{o['n']} cases; 95% interval {pct(lo)}-{pct(hi)}), "
        f"dev {pct(fsc['dev']['pass_rate'])}, hold-out {pct(fsc['holdout']['pass_rate'])}. Baseline was {pct(base['scorecard']['overall']['pass_rate'])}. "
        f"Optimizer stopped because: {opt['stop_reason']}.", "",
        "> This number is a measurement on an eval set generated by a small model from the same documents. Treat it as a regression signal, not a guarantee. "
        f"With {o['n']} cases one case moves the score by {100 / o['n']:.0f} points.", "",
    ]
    health = ctx.get("health")
    if health:
        lines += ["## 0. Run health", f"Run status: **{health['status']}**", ""]
        for st in health["stages"]:
            lines.append(f"- stage `{st['name']}`: {st['status']} ({st['seconds']}s)")
        if health["warnings"]:
            lines += ["", "Warnings raised during the run:"] + [f"- {w}" for w in health["warnings"]]
        else:
            lines += ["", "No warnings were raised."]
        lines.append("")
    lines += ["## 1. Groundability", f"Status: **{gr['status'].upper()}** - {gr['message']}", ""]
    for t in gr["topics"]:
        lines.append(f"- `{t['verdict']}` {t['topic']}" + (f" (coverage {t['coverage']})" if t.get("coverage") is not None else "") + ("".join(f" - {n}" for n in t.get("notes", []))))
    if gr["known_gaps"]:
        lines += ["", "Removed from scope and turned into refusals: " + "; ".join(gr["known_gaps"])]
    lines += ["", "## 2. What was generated"]
    lines += [f"- Documents: {', '.join(defn['knowledge']['documents'])}",
              f"- Retrieval (final): {defn['knowledge']['retrieval']['method']} top_k={defn['knowledge']['retrieval']['top_k']} chunk={defn['knowledge']['chunking']}",
              f"- System-prompt rules: {len(defn['system_prompt']['rules'])} ({sum(1 for r in defn['system_prompt']['rules'] if r['origin'] != 'base')} added by the optimizer)",
              f"- Tools attached: {', '.join(defn['tools']) or 'none'}"]
    for n, d in defn["tool_selection"].items():
        lines.append(f"  - `{n}`: {'ATTACHED' if d['attached'] else 'not attached'} - {'; '.join(d['reasons'])}")
    lines += ["", "## 3. Scorecard", "", scorecard_markdown(base, hist, fsc), ""]
    lines += ["## 4. Change log (what changed, why, which failures, score before -> after)"]
    if not hist:
        lines.append("No iterations were run.")
    for h in hist:
        lines.append(f"\n### Iteration {h['iteration']} - {h['decision']}")
        lines.append(f"Dev {pct(h['score_before']['dev'])} -> {pct(h['score_after']['dev'])}; hold-out {pct(h['score_before']['holdout'])} -> {pct(h['score_after']['holdout'])}. "
                     f"Failures before: {h['failure_counts_before']}. Targeted: {h['failures_targeted']}. Now passing: {h['fixed']}. Newly failing: {h['regressed']}.")
        for t in h.get("ablation_trials", []):
            lines.append(f"- ablation trial `{t['category']}` alone: dev -> {pct(t['dev_after'])}, hold-out -> {pct(t['holdout_after'])} ({'kept' if t['accepted'] else 'rejected'})")
        for c in h["changes"]:
            lines.append(f"- **{c['type']}** `{c['target']}` ({c.get('category', '')}): {c.get('before')} -> {c.get('after')}  \n  why: {c.get('why', '')}  cases: {c.get('cases')}")
    lines += ["", "## 5. What still fails, and why"]
    ff = opt["final_failures"]
    if not ff:
        lines.append("Nothing failed on this eval set. That does not mean the agent is perfect - see section 6.")
    for f in ff:
        lines.append(f"- **{f['id']}** [{f['category']}] {f['question']}  \n  diagnosis: {f['why']}. judge notes: {'; '.join(f['notes']) or '-'}  \n  agent said: _{f['answer'][:200]}_")
    lines += ["", "## 6. Why you can (and cannot) trust these numbers"]
    st = ev["stats"]
    acc = sum(v for k2, v in st.items() if k2.startswith("accepted:"))
    rej = sum(v for k2, v in st.items() if k2.startswith("rejected:"))
    rej_kinds = ", ".join(key.split(":", 1)[1] + "=" + str(v) for key, v in st.items() if key.startswith("rejected:")) or "none"
    lines.append(f"- Eval set: {ev['total']} cases {ev['counts']}. {acc} accepted, {rej} generated candidates were rejected by machine verification ({rej_kinds}). "
                 "Expected facts are verified verbatim against the source text.")
    for w in ev.get("warnings", []):
        lines.append(f"- **WARNING:** {w}")
    if cal.get("ran"):
        flag = "" if (cal["reliability"] or 0) >= 0.75 else "  **WARNING: judge reliability below 0.75 - treat LLM-rescued verdicts with suspicion.**"
        lines.append(f"- Judge calibration (known-answer canaries: gold / wrong / padded-wrong / altered-number / fact-order swap): reliability **{cal['reliability']}**, by kind {cal['by_kind']}.{flag}")
    else:
        lines.append("- Judge calibration did not run; only deterministic checks were used.")
    lines.append("- Deterministic checks (verbatim facts, numbers present in context, verified evidence quotes) outrank the LLM judge; the LLM may only rescue a paraphrased fact or confirm a grounding doubt, and needs a verifiable quote.")
    gap = (fsc["dev"]["pass_rate"] or 0) - (fsc["holdout"]["pass_rate"] or 0)
    lines.append(f"- Dev vs hold-out gap: {gap * 100:+.0f} points" + (" - the optimizer likely overfit the dev cases." if gap > 0.15 else "."))
    lines.append("- Agent, eval generator and (by default) judge are the same small model; self-preference and shared blind spots are possible. Use `--judge-model` with a different model to reduce this.")
    lines.append(f"- Budget: {ctx['budget']}")
    return "\n".join(lines) + "\n"
